// Запасные снимки (можно использовать вместо любых выше):
//   photo-1743525407528-19a48569192a  — ресторан на берегу
//   photo-1786023827489-374db4a0a5e5  — лимоны на фоне неба
//   photo-1685209342390-79ac55eb7ac0  — лимон на ветке
//   photo-1696519668803-05212f0bb237  — белое здание с синими дверями

export function imgUrl(value, width = 800) {
  if (!value) return '';
  if (/^https:\/\//.test(value)) return value;
  if (/^photo-/.test(value)) return `https://images.unsplash.com/${value}?auto=format&fit=crop&w=${width}&q=75`;
  return '';
}
